    [Fact]
    public void All1780IndependentSourceInstructionAndDecimalVectorsMatchExactWordsMasksAndIndexes()
    {
        int count = 0;
        foreach (string line in Corpus.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            string[] f = line.Split(','); uint U(string s) => uint.Parse(s, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            var r = RetailNpcNativeHeading.Atan2(U(f[0]), U(f[1]), Environment);
            Assert.True(r.Success, line + " : " + r.Detail); Assert.Equal(U(f[2]), r.ReturnWord);
            Assert.Equal(f[3].Length == 0 ? Array.Empty<uint>() : f[3].Split(':').Select(U).ToArray(), r.ExplicitStatusMasks);
            Assert.Equal(f[4] == "-" ? (int?)null : int.Parse(f[4], CultureInfo.InvariantCulture), r.TableIndex); count++;
            Assert.False(r.NativeTargetExecuted); Assert.False(r.ArithmeticStickyFlagsVerified);
        }
        Assert.Equal(1780, count);
    }
