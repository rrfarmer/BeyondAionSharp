	private readonly bool _ok;
	private readonly string _accountName;
	private readonly IReadOnlyList<WorldMapSummary> _worldMaps;

	public SmL2AuthLoginCheck(bool ok, string accountName, IReadOnlyList<WorldMapSummary>? worldMaps = null)
		: base(PacketOpCode)
	{
		_ok = ok;
		_accountName = accountName;
		_worldMaps = worldMaps ?? Array.Empty<WorldMapSummary>();
	}

	protected override void WritePayload(PacketBuffer buffer, GameCrypt crypt)
	{
		// Java parity: network/aion/serverpackets/SM_L2AUTH_LOGIN_CHECK.writeImpl.
		buffer.WriteD(_ok ? 0 : 1);
		buffer.WriteB(StandardData);
		buffer.WriteH(_worldMaps.Count);
		foreach (var map in _worldMaps)
		{
			buffer.WriteD(map.MapId);
			buffer.WriteH(map.IsInstance ? 0 : map.TwinCount);
		}

		buffer.WriteS(_accountName);
	}
}
