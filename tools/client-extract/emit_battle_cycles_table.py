"""Transcribe battle_cycles.tsv into BattleCycles.cs. See extract_battle_cycles.py for the claim."""
from __future__ import annotations

import argparse
import collections
import pathlib

#: Each retail handler this table drives, and the field it becomes. `cycle` is `on_battle_timer`; the
#: rest are places retail arms a timer from, and a rotation with no arming rung never runs at all.
HANDLERS = [
    ("cycle", "Cycle", "The rotation itself, chosen by which timer fired."),
    ("on_enter_attack_state", "OnEnterAttackState", "Arms the chain when the fight starts."),
    ("on_message", "OnMessage", "Arms the chain when another npc calls."),
    ("on_attacked", "OnAttacked", "Arms the chain on being hit."),
    ("on_spelled", "OnSpelled", "Arms the chain on being spelled."),
    ("on_wake_up", "OnWakeUp", "Arms the chain on waking."),
    ("on_see_npc", "OnSeeNpc", "Arms the chain on seeing an npc."),
    ("on_see_user", "OnSeeUser", "Arms the chain on seeing a player."),
    ("on_die", "OnDie", "What the encounter leaves behind when it dies."),
    ("on_leave_attack_state", "OnLeaveAttack", "What it does when the fight ends without dying."),
]

HEADER = '''// <auto-generated>
//     Generated by tools/client-extract/emit_battle_cycles_table.py from out/battle_cycles.tsv.
//     Do not edit by hand; edit the extractor and re-run.
// </auto-generated>
using Aion.GameServer.Ai.Pattern;
using Aion.GameServer.Controllers.Attack;
using Aion.GameServer.Model.Templates.Npcskill;

namespace Aion.GameServer.Handlers.AI;

/// <summary>
/// Combat rotations: {patterns} retail patterns across {npcs} npcs, {actions} actions.
/// </summary>
/// <remarks>
/// What a boss does <b>during</b> the fight, as opposed to <see cref="IdleCycles"/>, which is what an
/// npc does while nothing is happening. Retail arms a battle timer on entering combat and every timer
/// branch arms the next link itself, so a fight is a chain of timers rather than an HP ladder.
/// <para>
/// The arming rung runs on <c>on_enter_attack_state</c>; the cycle rungs run when the timer fires and
/// are guarded by its indicator, so two rotations on different indicators do not disturb each other.
/// <see cref="PatternAi"/> cancels every timer when the fight ends, which is why nothing here needs to
/// clean up after itself.
/// </para>
/// <para>
/// <b>The skills are real too.</b> Retail names them by index into the npc's own ordered list, which
/// this port could not resolve until that list was found in the 5.8 server dump; see
/// <c>extract_npc_skill_lists.py</c>. A rotation is only taken if the owning npc's list answers every
/// index it uses, so a boss here never casts a skill picked by position out of the wrong list.
/// </para>
/// <para>
/// <b>Spawn groups are real here.</b> The idle table spawns into <c>Untracked</c> because nothing there
/// refers back to what it placed; a rotation that despawns its adds needs the group it spawned into.
/// </para>
/// </remarks>
internal static class BattleCycles
{{
    /// <summary>What the npc does on entering combat -- normally arming the first timer.</summary>
    internal static PatternBranch[] ArmingRungsFor(int npcId)
        => OnEnterAttackState.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>Rungs that arm a timer when another npc sends a message.</summary>
    internal static PatternBranch[] MessageRungsFor(int npcId)
        => OnMessage.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>Rungs that arm a timer on being hit.</summary>
    internal static PatternBranch[] AttackedRungsFor(int npcId)
        => OnAttacked.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>Rungs that arm a timer on being spelled.</summary>
    internal static PatternBranch[] SpelledRungsFor(int npcId)
        => OnSpelled.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>Rungs that arm a timer on waking.</summary>
    internal static PatternBranch[] WakeRungsFor(int npcId)
        => OnWakeUp.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>Rungs that arm a timer on seeing another npc.</summary>
    internal static PatternBranch[] SeeNpcRungsFor(int npcId)
        => OnSeeNpc.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>Rungs that arm a timer on seeing a player.</summary>
    internal static PatternBranch[] SeeUserRungsFor(int npcId)
        => OnSeeUser.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>What the npc leaves behind when it dies.</summary>
    internal static PatternBranch[] DeathRungsFor(int npcId)
        => OnDie.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>What it does when the fight ends without it dying.</summary>
    internal static PatternBranch[] LeaveFightRungsFor(int npcId)
        => OnLeaveAttack.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>What each timer does when it fires, in retail's order.</summary>
    internal static PatternBranch[] CycleRungsFor(int npcId)
        => Cycle.TryGetValue(npcId, out PatternBranch[]? rungs) ? rungs : [];

    /// <summary>Every npc this table drives.</summary>
    internal static IEnumerable<int> Npcs => Cycle.Keys;

'''

FOOTER = '''}
'''


def guard_code(token: str) -> str:
    kind, _, argument = token.partition(":")
    if kind == "timer":
        return f"When.Timer({argument})"
    if kind == "hp_below":
        return f"When.HpBelow({argument})"
    if kind == "hp_between":
        low, high = argument.split(":")
        return f"When.HpBetween({low}, {high})"
    if kind == "set_flag_var":
        return f"When.FirstTime({argument})"
    if kind == "unset_flag_var":
        return f"When.Consuming({argument})"
    if kind == "set_world_flag_var":
        return f"When.FirstTimeInWorld({argument})"
    if kind == "unset_world_flag_var":
        return f"When.ConsumingWorld({argument})"
    if kind == "is_world_flag_var":
        return f"When.WorldFlagSet({argument})"
    if kind == "message":
        return f"When.Message({argument})"
    if kind == "flying":
        return f"When.{argument}Flying"
    if kind == "chance":
        return f"When.Chance({argument})"
    raise ValueError(f"unknown guard {token}")


def action_code(row: dict) -> str:
    kind = row["kind"]
    if kind == "spawn":
        npc, count, live, group = row["a1"], row["a2"], row["a3"], row["group"]
        place, x, y, z = row["place"], row["x"], row["y"], row["z"]
        # Retail's despawn_at_attack_state: the add goes when the fight does.
        suffix = ""
        if place.startswith("for_the_fight_"):
            place, suffix = place[len("for_the_fight_"):], "ForTheFight"
        if place == "self":
            return f"Do.SpawnNear{suffix}({npc}, {group}, {count}, 0f, {live})"
        if place == "offset":
            return f"Do.SpawnOffset{suffix}({npc}, {group}, {x}f, {y}f, {live}, {z}f)"
        spots = ", ".join(f"new SpawnSpot({x}f, {y}f, {z}f)" for _ in range(max(1, int(count))))
        return f"Do.SpawnAt{suffix}({npc}, {group}, {live}, {spots})"
    if kind == "skill":
        return f"Do.SkillOn(NpcSkillTargetAttribute.{row['place']}, {row['a1']})"
    if kind == "skill_at":
        return f"Do.SkillOn{row['place']}({row['a1']})"
    if kind == "arm":
        return f"Do.ArmTimer({row['a1']}, {row['a2']})"
    if kind == "despawn":
        return f"Do.Despawn({row['a1']})"
    if kind == "spawn_on_target":
        return (f"Do.SpawnOnTarget({row['a1']}, {row['group']}, {row['a2']}, {row['x']}f, "
                f"{row['a3']}, {int(float(row['z']))}, {row['y']}f)")
    if kind == "spawn_near":
        return f"Do.SpawnNear({row['a1']}, {row['group']}, {row['a2']}, {row['x']}f, {row['a3']})"
    if kind == "switch_to":
        return f"Do.SwitchTarget(AggroTarget.{row['place']})"
    if kind == "hate":
        return f"Do.HateMessageParam({row['a1']})"
    if kind == "switch":
        return "Do.TargetMessageParam()"
    if kind == "attack":
        return "Do.AttackMostHating()"
    if kind == "despawn_self":
        return "Do.DespawnSelf()"
    if kind == "say":
        return f"Do.Say({row['a1']}, {row['a2']})"
    if kind == "sysmsg":
        return f"Do.SystemMessage({row['a1']}, {row['a2']})"
    if kind == "var":
        return f'Do.SetSpawnVariable("{row["place"]}", {row["a1"]}, {row["a2"]})'
    if kind == "broadcast":
        return f"Do.Broadcast({row['a1']}, {row['a2']}f)"
    raise ValueError(f"unknown action {kind}")


#: How many npcs go into one generated method.
#:
#: A single initializer holding every npc **overflowed the stack the first time the class was touched**
#: -- in the type initializer itself, not in any test harness quirk, so it would have taken the live
#: server down the same way the moment a bound npc entered combat. The table is built by a chain of
#: small methods instead. 100 npcs per method keeps each one well inside what the runtime will start.
CHUNK = 100


def write_table(out, field: str, summary: str, branches, meta, names) -> None:
    npcs = sorted(branches)
    chunks = [npcs[i:i + CHUNK] for i in range(0, len(npcs), CHUNK)] or [[]]

    out.write("    /// <summary>" + summary + "</summary>\n")
    out.write("    private static readonly IReadOnlyDictionary<int, PatternBranch[]> "
              + field + " =\n")
    out.write("        Build" + field + "();\n\n")
    out.write("    private static Dictionary<int, PatternBranch[]> Build" + field + "()\n")
    out.write("    {\n")
    out.write("        Dictionary<int, PatternBranch[]> rungs = "
              "new Dictionary<int, PatternBranch[]>();\n")
    for index in range(len(chunks)):
        out.write("        " + field + str(index) + "(rungs);\n")
    out.write("        return rungs;\n    }\n\n")

    for index, chunk in enumerate(chunks):
        out.write("    private static void " + field + str(index)
                  + "(Dictionary<int, PatternBranch[]> rungs)\n    {\n")
        for npc in chunk:
            out.write(f"        rungs[{npc}] = [  // {names[npc]}\n")
            for branch in sorted(branches[npc]):
                priority, guards = meta[(npc, branch)]
                tokens = [guard_code(t) for t in guards.split("|") if t]
                condition = "When.Always" if not tokens else "[" + ", ".join(tokens) + "]"
                body = ",\n".join("                " + action_code(r) for r in branches[npc][branch])
                out.write(f'            AiPattern.Branch({priority}, "rung {branch}", {condition},\n')
                out.write(body + "),\n")
            out.write("        ];\n")
        out.write("    }\n\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", type=pathlib.Path)
    ap.add_argument("out", type=pathlib.Path)
    args = ap.parse_args()

    lines = args.tsv.read_text(encoding="utf-8").splitlines()
    header = lines[0].split("\t")
    tables: dict[str, dict] = collections.defaultdict(
        lambda: collections.defaultdict(lambda: collections.defaultdict(list)))
    meta: dict[tuple[str, int, int], tuple[int, str]] = {}
    names: dict[int, str] = {}
    actions = 0
    for line in lines[1:]:
        row = dict(zip(header, line.split("\t")))
        npc, branch = int(row["npc"]), int(row["branch"])
        names[npc] = row["pattern"]
        meta[(row["handler"], npc, branch)] = (int(row["priority"]), row["guards"])
        tables[row["handler"]][npc][branch].append(row)
        actions += 1

    with args.out.open("w", encoding="utf-8", newline="\n") as out:
        out.write(HEADER.format(patterns=len(set(names.values())), npcs=len(names), actions=actions))
        for handler, field, summary in HANDLERS:
            # Emitted even when empty: the accessors above name every field unconditionally, and a
            # handler with no rows today is the normal state for the rarer ones rather than a reason
            # to leave a dangling name. `on_leave_attack_state` is exactly that -- every branch retail
            # puts there is currently unsayable, and the field is an empty dictionary saying so.
            write_table(out, field, summary, tables[handler],
                        {(n, b): v for (h, n, b), v in meta.items() if h == handler}, names)
        out.write(FOOTER)

    print(f"{len(set(names.values()))} patterns, {len(names)} npcs, {actions} actions -> {args.out}")


if __name__ == "__main__":
    main()
