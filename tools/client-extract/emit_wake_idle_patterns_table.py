def action_code(row):
    """The idle vocabulary, plus the casts only this table takes."""
    kind = row["kind"]
    if kind not in ("skill", "skill_now"):
        return idle_action_code(row)
    # A hazard casts and leaves in one rung. `Do.SkillOn` queues, and the queue is drained by the attack
    # loop only while the npc has somebody to hate -- so a queued cast from an npc that despawns in the
    # same breath never fires, which NpcSkillCasting has said in a comment since long before this table.
    if kind == "skill_now":
        return f"Do.SkillOnSelfNow({row['a1']})"
    target = row["place"]
    if target.startswith("@"):
        return f"Do.SkillOn{target[1:]}({row['a1']})"
    return f"Do.SkillOn(NpcSkillTargetAttribute.{target}, {row['a1']})"

HANDLERS = [("on_wake_up", "OnWakeUp", "What it does the moment it appears."),
            ("on_idle_timer", "OnIdleTimer", "What it does each time its own timer fires.")]

XML_HEADER = '''<?xml version="1.0" encoding="UTF-8"?>
<!--
    Generated by tools/client-extract/emit_wake_idle_patterns_table.py from
    out/wake_idle_patterns.tsv. Do not edit by hand; edit the extractor and re-run.

    What a retail npc does the moment it appears, and each time its own idle timer fires:
    {patterns} patterns across {npcs} npcs, {actions} actions.

    Two handlers share this file and an npc may appear under both, so each element names its own.
    Branch order is the order written here; retail's lists are first-match-wins.

    These rungs carry no spawn group. Nothing here refers back to what it placed, which is retail's
    SPAWN_ID_NONE, so PatternTableData reads an absent group as untracked.

    This was 23,898 lines of generated C#. See PatternTableLoader for how a guard token and an
    action row become the guards and actions a PatternAi runs.
-->
<pattern_table>
'''


def escape(value: str) -> str:
    """XML attribute escaping."""
    return (value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def write_table(out, handler, branches, meta, names):
    """One handler's npcs, as <npc handler="..."> elements."""
    for npc in sorted(branches):
        label = names[npc].replace("--", "-")
        out.write(f'\t<npc id="{npc}" handler="{handler}">  <!-- {label} -->\n')
        for branch in sorted(branches[npc]):
            priority, guards = meta[(npc, branch)]
            out.write(f'\t\t<branch priority="{priority}" comment="rung {branch}">\n')
            for token in [t for t in guards.split("|") if t]:
                out.write(f'\t\t\t<guard token="{escape(token)}" />\n')
            for row in branches[npc][branch]:
                out.write(
                    f'\t\t\t<action kind="{escape(row["kind"])}"'
                    f' a1="{row["a1"]}" a2="{row["a2"]}" a3="{row["a3"]}"'
                    f' place="{escape(row["place"])}"'
                    f' x="{row["x"]}" y="{row["y"]}" z="{row["z"]}" />\n')
            out.write(f'\t\t</branch>\n')
        out.write(f'\t</npc>\n')


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", type=pathlib.Path)
    ap.add_argument("out", type=pathlib.Path)
    args = ap.parse_args()

    lines = args.tsv.read_text(encoding="utf-8").splitlines()
    header = lines[0].split("\t")
    tables = collections.defaultdict(lambda: collections.defaultdict(lambda: collections.defaultdict(list)))
    meta = {}
    names = {}
    actions = 0
    for line in lines[1:]:
        row = dict(zip(header, line.split("\t")))
        npc, branch = int(row["npc"]), int(row["branch"])
        names[npc] = row["pattern"]
        meta[(row["handler"], npc, branch)] = (int(row["priority"]), row["guards"])
        tables[row["handler"]][npc][branch].append(row)
        actions += 1

    with args.out.open("w", encoding="utf-8", newline="\n") as out:
        out.write(XML_HEADER.format(patterns=len(set(names.values())), npcs=len(names), actions=actions))
        for handler, _field, _summary in HANDLERS:
            write_table(out, handler, tables[handler],
                        {(n, b): v for (h, n, b), v in meta.items() if h == handler}, names)
        out.write("</pattern_table>" + "\n")

    # A double dash in a comment is an XML error that reads as a thousand unrelated red tests.
    xml.dom.minidom.parse(str(args.out))

    print(f"{len(set(names.values()))} patterns, {len(names)} npcs, {actions} actions -> {args.out}")


if __name__ == "__main__":
    main()
