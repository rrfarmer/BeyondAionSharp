#!/usr/bin/env python3
"""Re-run every generator that feeds committed data, and report crashes and drift.

WHY THIS EXISTS
---------------
Five scripts here write tables into `out/`, which are then emitted as generated C# and shipped. All
five are invoked by hand, and nothing re-runs them. So a script can stop working and stay broken:

> `extract_gate_squads.py` raised `ValueError: too many values to unpack` on **every** run for as long
> as it had existed. `Carry attack_target_after_spawn through the guard table` added a sixth field to
> `spawns_in()` ten minutes after `Wire the fortress gates` started importing it and unpacking exactly
> five. The committed table was fine -- it predated the sixth field -- so nothing looked wrong, and the
> gates simply could not be regenerated. The next person to try would have blamed their own change.

This runs all five and diffs each against what is committed. It is the check that would have caught
that the same day.

WHAT DRIFT MEANS
----------------
A drift report is **not** automatically a defect. It means the committed table no longer matches what
the current script produces from the current patterns, which happens for three quite different reasons:

* the script was fixed and the table has not been regenerated -- regenerate it;
* the script was changed and the change was wrong -- fix the script;
* the table was hand-edited after generation -- which the `<auto-generated>` headers forbid, and this
  is how you would find out.

It cannot tell you which. It tells you the three files that need looking at instead of eighty.

BOTH HALVES OF THE PIPELINE
---------------------------
The patterns become a `.tsv` in `out/`, and the `.tsv` becomes generated C# in `src/`. Checking only the
first half leaves the case where a table is correct and the C# beside it is stale -- which is the more
dangerous of the two, because the `.tsv` is a working file and the `.cs` is what actually ships.

So the emit step is checked the same way: each `emit_*.py` is run from the **committed** table into a
temp file and diffed against the committed `.cs`. Running from the committed table rather than the
freshly extracted one is deliberate: it keeps the two halves independent, so a drift report names which
step is out of date instead of blaming both.

EXIT CODES
----------
* **0** -- everything ran and reproduced what is committed.
* **1** -- something crashed or drifted.
* **2** -- nothing was wrong, but the retail dump was absent so only the emit half could be checked.

2 is deliberately distinct from both. A CI job that treats "could not check" as "checked and fine" is
worse than no CI job, and one that treats it as a failure would go red on every machine without the
dump. The caller has to decide which it wants, so the tool refuses to decide for it.

Usage:  python regen_check.py [--xml DIR]
"""
import argparse
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
BINDING = HERE / "out" / "ai_binding.tsv"

# (script, committed table, extra args). The tiamat extractor is listed twice because normal and hard
# mode are one script with a --pattern switch and two committed tables; running only the default would
# leave the hard table unchecked, which is exactly the kind of gap this script exists to close.
GENERATORS = [
    ("extract_guard_reinforcements.py", "guard_reinforcements.tsv", []),
    ("extract_gate_squads.py", "gate_squads.tsv", []),
    ("extract_vritra_callers.py", "vritra_callers.tsv", []),
    ("extract_tiamat_rotation.py", "tiamat_rotation.tsv", []),
    ("extract_tiamat_rotation.py", "tiamat_rotation_hard.tsv",
     ["--pattern", "IDTiamat_Hard_Tiamat_Dragon_Dying"]),
]

# Same job, different CLI: it takes the output path positionally and has no --out.
POSITIONAL_OUT = [("extract_guard_calls.py", "guard_calls.tsv"),
                  ("extract_siege_death_calls.py", "siege_death_calls.tsv"),
                  ("extract_protector_calls.py", "protector_calls.tsv"),
                  ("extract_fortress_killers.py", "fortress_killers.tsv"),
                  ("extract_pull_calls.py", "pull_calls.tsv"),
                  ("extract_guard_answers.py", "guard_answers.tsv"),
                  ("extract_tiamat_beacons.py", "tiamat_beacons.tsv"),
                  ("extract_idle_spawns.py", "idle_spawns.tsv"),
                  ("extract_idle_cycles.py", "idle_cycles.tsv")]

# Reads the world files rather than the pattern dump, so it takes a different first argument
# and cannot join POSITIONAL_OUT above.
WORLD_EXTRACTORS = [("extract_spawn_conditions.py", "spawn_conditions.tsv")]

# Writes into game-server data rather than out/, because the server reads it directly.
GAME_DATA_EXTRACTORS = [("extract_gated_spawns.py",
                         "game-server/data/static_data/spawns/gated/gated_spawns.tsv")]

# (emitter, committed .cs, argv builder). The tiamat emitter takes the output path FIRST and its tables
# as repeated --table switches, so it cannot share the others' shape.
GEN = pathlib.Path("src/Aion.GameServer/Handlers/AI")
EMITTERS = [
    ("emit_guard_table.py", GEN / "GuardReinforcements.cs",
     lambda out: [str(HERE / "out" / "guard_reinforcements.tsv"), out]),
    ("emit_gate_table.py", GEN / "GateSquads.cs",
     lambda out: [str(HERE / "out" / "gate_squads.tsv"), out]),
    ("emit_vritra_table.py", GEN / "VritraCallers.cs",
     lambda out: [str(HERE / "out" / "vritra_callers.tsv"), out]),
    ("emit_guard_calls_table.py", GEN / "GuardCalls.cs",
     lambda out: [str(HERE / "out" / "guard_calls.tsv"), out]),
    ("emit_pull_calls_table.py", GEN / "PullCalls.cs",
     lambda out: [str(HERE / "out" / "pull_calls.tsv"), out]),
    ("emit_guard_answers_table.py", GEN / "GuardAnswers.cs",
     lambda out: [str(HERE / "out" / "guard_answers.tsv"), out]),
    ("emit_tiamat_beacons_table.py", GEN / "TiamatBeacons.cs",
     lambda out: [str(HERE / "out" / "tiamat_beacons.tsv"), out]),
    ("emit_idle_spawns_table.py", GEN / "IdleSpawns.cs",
     lambda out: [str(HERE / "out" / "idle_spawns.tsv"), out]),
    ("emit_idle_cycles_table.py", GEN / "IdleCycles.cs",
     lambda out: [str(HERE / "out" / "idle_cycles.tsv"), out]),
    ("emit_fortress_killers_table.py", GEN / "FortressKillers.cs",
     lambda out: [str(HERE / "out" / "fortress_killers.tsv"), out]),
    ("emit_protector_calls_table.py", GEN / "ProtectorCalls.cs",
     lambda out: [str(HERE / "out" / "protector_calls.tsv"), out]),
    ("emit_siege_death_calls_table.py", GEN / "SiegeDeathCalls.cs",
     lambda out: [str(HERE / "out" / "siege_death_calls.tsv"), out]),
    ("emit_tiamat_table.py", GEN / "TiamatRotation.cs",
     lambda out: [out,
                  "--table", f"219362={HERE / 'out' / 'tiamat_rotation.tsv'}",
                  "--table", f"236277={HERE / 'out' / 'tiamat_rotation_hard.tsv'}"]),
]


def run(script, args):
    result = subprocess.run([sys.executable, str(HERE / script), *args],
                            capture_output=True, text=True, errors="replace")
    return result.returncode, result.stderr


def check_emitters(problems):
    """Each emitter, run from the committed table, against the committed C#."""
    repo = HERE.parents[1]
    with tempfile.TemporaryDirectory() as tmp:
        for script, target, argv in EMITTERS:
            out = str(pathlib.Path(tmp) / target.name)
            code, err = run(script, [str(a) for a in argv(out)])
            label = f"{script} -> {target.name}"
            if code != 0:
                tail = "\n      ".join(err.strip().splitlines()[-3:])
                problems.append(f"{label}: CRASHED\n      {tail}")
                print(f"  CRASH    {label}")
                continue
            compare(label, pathlib.Path(out), repo / target, problems)


def compare(label, produced, committed, problems):
    if not committed.exists():
        problems.append(f"{label}: no committed table at {committed.name}")
        return
    want = sorted(committed.read_text(encoding="utf-8").splitlines())
    got = sorted(produced.read_text(encoding="utf-8").splitlines())
    if want == got:
        print(f"  ok       {label}")
        return
    added = len([ln for ln in got if ln not in set(want)])
    removed = len([ln for ln in want if ln not in set(got)])
    problems.append(f"{label}: DRIFT, {added} rows added and {removed} removed vs {committed.name}")
    print(f"  DRIFT    {label}  (+{added} -{removed})")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--xml", default="D:/Aion58ServerTesting/Server/Map/XML")
    args = ap.parse_args()

    problems = []

    # The emit half reads only committed files, so it is checked either way. A missing pattern dump
    # should not mean "nothing to check" when half the pipeline is checkable without it.
    print("emit: committed table -> committed C#")
    check_emitters(problems)

    if not pathlib.Path(args.xml).is_dir():
        print(f"\nretail pattern dump not found at {args.xml}; extract half skipped", file=sys.stderr)
        return 1 if problems else 2

    print("\nextract: retail patterns -> committed table")
    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = pathlib.Path(tmp)
        for script, table, extra in GENERATORS:
            out = tmpdir / table
            code, err = run(script, [args.xml, str(BINDING), "--out", str(out), *extra])
            if code != 0:
                tail = "\n      ".join(err.strip().splitlines()[-3:])
                problems.append(f"{script} -> {table}: CRASHED\n      {tail}")
                print(f"  CRASH    {script} -> {table}")
                continue
            compare(f"{script} -> {table}", out, HERE / "out" / table, problems)

        for script, table in POSITIONAL_OUT:
            out = tmpdir / table
            code, err = run(script, [args.xml, str(BINDING), str(out)])
            if code != 0:
                tail = "\n      ".join(err.strip().splitlines()[-3:])
                problems.append(f"{script} -> {table}: CRASHED\n      {tail}")
                print(f"  CRASH    {script} -> {table}")
                continue
            compare(f"{script} -> {table}", out, HERE / "out" / table, problems)

    print()
    if not problems:
        print("every generator and emitter runs and reproduces what is committed")
        return 0
    print(f"{len(problems)} problem(s):")
    for p in problems:
        print(f"  {p}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
