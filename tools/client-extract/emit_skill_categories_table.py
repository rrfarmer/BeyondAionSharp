"""Transcribe skill_categories.tsv into skills/retail_skill_categories.xml.

See extract_skill_categories.py for the claim, and SkillCategoryData for how it is read.
"""
from __future__ import annotations

import argparse
import collections
import pathlib
import xml.dom.minidom

XML_HEADER = '''<?xml version="1.0" encoding="UTF-8"?>
<!--
    Generated by tools/client-extract/emit_skill_categories_table.py from out/skill_categories.tsv.
    Do not edit by hand; edit the extractor and re-run.

    Retail's own skill categories: {rows} skills across {kinds} categories.

    Retail's AI asks about these on `on_friend_spelled`: was my friend just hit with a physical
    debuff, a mental one, or healed. This port had no category for a skill, so the condition could
    not be read at all.

    Grouped by category rather than listed per skill, because 2,052 rows of one skill each is
    larger and says less. Skills retail gives no category are absent; an absent skill has none.

    **This is not derivable from skill_templates.xml.** Retail's PHYSICAL_DEBUFF is mostly
    skilltype="MAGICAL" here, and this port's MAGICAL/DEBUFF signature covers 1,382 skills of which
    1,248 have no retail category at all. See the extractor for the measurement.
-->
<skill_categories>
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", type=pathlib.Path)
    ap.add_argument("out", type=pathlib.Path)
    args = ap.parse_args()

    by_category: dict[str, list[int]] = collections.defaultdict(list)
    rows = 0
    for line in args.tsv.read_text(encoding="utf-8").splitlines()[1:]:
        skill, category = line.split("\t")
        by_category[category].append(int(skill))
        rows += 1

    body = [XML_HEADER.format(rows=rows, kinds=len(by_category))]
    for category in sorted(by_category):
        ids = sorted(by_category[category])
        body.append(f'\t<category name="{category}" count="{len(ids)}">\n')
        # Wrapped rather than one id per line: 2,052 elements would be 2,052 lines for one integer
        # each, and these are read as a set.
        for start in range(0, len(ids), 16):
            body.append("\t\t<skills>" + " ".join(str(i) for i in ids[start:start + 16])
                        + "</skills>\n")
        body.append("\t</category>\n")
    body.append("</skill_categories>\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(body), encoding="utf-8", newline="\n")

    # Parsed before the run is called a success: an XML comment cannot contain `--`, and a generator
    # that writes one takes the whole suite down rather than one test.
    xml.dom.minidom.parse(str(args.out))
    print(f"{rows} skills across {len(by_category)} categories -> {args.out}")


if __name__ == "__main__":
    main()
